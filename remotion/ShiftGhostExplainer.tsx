import React from "react";
import { AbsoluteFill, Html5Audio, Sequence, interpolate, staticFile, useVideoConfig } from "remotion";
import { C } from "./theme";
import { ContextDisappears } from "./scenes/ContextDisappears";
import { AnswersThroughGhost, answerArrival } from "./scenes/AnswersThroughGhost";
import { EvidenceRail, EVIDENCE_START, EVIDENCE_STEP, evidenceSnap } from "./scenes/EvidenceRail";
import { CLAIM_AT, MorningClaims, PRINT_AT } from "./scenes/MorningClaims";
import { PatternReveal, lightAt } from "./scenes/PatternReveal";
import { EndCard, EYES_ON } from "./scenes/EndCard";
import type { ExplainerProps } from "./schema";

export { explainerSchema, defaultExplainerProps, EXPLAINER_FPS, EXPLAINER_DURATION } from "./schema";
export type { ExplainerProps } from "./schema";

/** Scene boundaries in frames at 30 fps (45 s total). */
export const SCENES = [
  { name: "The shift ends", from: 0, duration: 210 },
  { name: "Five answers through the ghost", from: 210, duration: 240 },
  { name: "Evidence snaps onto the rail", from: 450, duration: 270 },
  { name: "Luis claims three tasks", from: 720, duration: 240 },
  { name: "The ice-machine pattern", from: 960, duration: 240 },
  { name: "End card", from: 1200, duration: 150 },
] as const;

const Sfx: React.FC<{ at: number; file: string; volume: number; frames?: number; loop?: boolean }> = ({ at, file, volume, frames = 30, loop }) => {
  const { fps } = useVideoConfig();
  return (
    <Sequence name={`sfx ${file}`} from={at} durationInFrames={frames} premountFor={fps}>
      <Html5Audio src={staticFile(`sfx/${file}`)} volume={volume} loop={loop} />
    </Sequence>
  );
};

/** Ramp a looping hum in and out over its sequence. */
const Hum: React.FC<{ at: number; frames: number; peak: number }> = ({ at, frames, peak }) => {
  const { fps } = useVideoConfig();
  return (
    <Sequence name="sfx low-hum" from={at} durationInFrames={frames} premountFor={fps}>
      <Html5Audio
        src={staticFile("sfx/low-hum.wav")}
        loop
        volume={(f) => interpolate(f, [0, 20, frames - 25, frames], [0, peak, peak, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" })}
      />
    </Sequence>
  );
};

/**
 * Shift Ghost explainer. One component for 1920×1080 and 1080×1920; every
 * scene lays itself out from useVideoConfig().
 */
export const ShiftGhostExplainer: React.FC<ExplainerProps> = (props) => {
  const { fps } = useVideoConfig();
  const [s1, s2, s3, s4, s5, s6] = SCENES;
  return (
    <AbsoluteFill style={{ backgroundColor: C.night }}>
      <Sequence name={s1.name} from={s1.from} durationInFrames={s1.duration} premountFor={fps}>
        <ContextDisappears duration={s1.duration} location={props.location} />
      </Sequence>
      <Sequence name={s2.name} from={s2.from} durationInFrames={s2.duration} premountFor={fps}>
        <AnswersThroughGhost duration={s2.duration} answers={props.answers} />
      </Sequence>
      <Sequence name={s3.name} from={s3.from} durationInFrames={s3.duration} premountFor={fps}>
        <EvidenceRail duration={s3.duration} items={props.items} />
      </Sequence>
      <Sequence name={s4.name} from={s4.from} durationInFrames={s4.duration} premountFor={fps}>
        <MorningClaims duration={s4.duration} tasks={props.tasks} opener={props.opener} />
      </Sequence>
      <Sequence name={s5.name} from={s5.from} durationInFrames={s5.duration} premountFor={fps}>
        <PatternReveal duration={s5.duration} location={props.location} pattern={props.pattern} />
      </Sequence>
      <Sequence name={s6.name} from={s6.from} durationInFrames={s6.duration} premountFor={fps}>
        <EndCard duration={s6.duration} tagline={props.tagline} company={props.company} />
      </Sequence>

      {/* Mechanical sound-design placeholders (public/sfx, generated by scripts/generate-sfx.mjs) */}
      <Hum at={s1.from} frames={s1.duration} peak={0.1} />
      {Array.from({ length: 7 }).map((_, i) => (
        <Sfx key={`note-${i}`} at={s1.from + 8 + i * 13} file="led-tick.wav" volume={0.12} frames={6} />
      ))}
      {props.answers.map((_, i) => (
        <Sfx key={`arrive-${i}`} at={s2.from + answerArrival(i)} file="relay-click.wav" volume={0.3} frames={8} />
      ))}
      <Sfx at={s3.from + 6} file="thermal-print.wav" volume={0.18} frames={28} />
      {props.items.map((_, i) => (
        <React.Fragment key={`ev-${i}`}>
          <Sfx at={s3.from + EVIDENCE_START + i * EVIDENCE_STEP + 4} file="led-tick.wav" volume={0.1} frames={6} />
          <Sfx at={s3.from + evidenceSnap(i)} file="relay-click.wav" volume={0.32} frames={8} />
        </React.Fragment>
      ))}
      <Sfx at={s4.from + PRINT_AT} file="thermal-print.wav" volume={0.22} frames={28} />
      {CLAIM_AT.map((f, i) => (
        <Sfx key={`claim-${i}`} at={s4.from + f} file="stamp-thunk.wav" volume={0.45} frames={12} />
      ))}
      {Array.from({ length: props.pattern.mentions }).map((_, i) => (
        <Sfx key={`led-${i}`} at={s5.from + lightAt(i)} file="led-tick.wav" volume={0.22} frames={6} />
      ))}
      <Hum at={s6.from} frames={s6.duration} peak={0.08} />
      <Sfx at={s6.from + EYES_ON} file="relay-click.wav" volume={0.3} frames={8} />
    </AbsoluteFill>
  );
};
